const dictionaries = {
	en,
	"zh-Hans": zhHans,
	"zh-Hant": zhHant,
} as const satisfies Record<AppLocale, TranslationDictionary>;

type InterpolationValue = number | string;

export type Translate = (
	key: TranslationKey,
	values?: Record<string, InterpolationValue>
) => string;

export const translate = (
	locale: AppLocale,
	key: TranslationKey,
	values: Record<string, InterpolationValue> = {}
) => {
	const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;

	return interpolate(template, values);
};

export const getTranslator =
	(locale: AppLocale): Translate =>
	(key, values) =>
		translate(locale, key, values);

const interpolationPattern = /\{(\w+)(?:,\s*plural,[^}]*)?\}/g;

const interpolate = (
	template: string,
	values: Record<string, InterpolationValue>
) =>
	template.replace(interpolationPattern, (match, key: string) => {
		const value = values[key];

		return value === undefined ? match : String(value);
	});

