export const normalizeLocale = (
	value: null | string | undefined
): AppLocale | null => {
	if (!value) {
		return null;
	}

	const localeCandidates = value
		.split(",")
		.map((candidate) => candidate.split(";").at(0)?.trim().toLowerCase())
		.filter((candidate): candidate is string => Boolean(candidate));

	for (const candidate of localeCandidates) {
		const normalizedCandidate = candidate.replace("_", "-");
		const directLocale = localeAliases[normalizedCandidate];

		if (directLocale) {
			return directLocale;
		}

		if (normalizedCandidate.startsWith("zh-hant")) {
			return "zh-Hant";
		}

		if (normalizedCandidate.startsWith("zh-hans")) {
			return "zh-Hans";
		}

		if (normalizedCandidate.startsWith("zh")) {
			if (
				normalizedCandidate.includes("tw") ||
				normalizedCandidate.includes("hk") ||
				normalizedCandidate.includes("mo")
			) {
				return "zh-Hant";
			}

			return "zh-Hans";
		}

		if (normalizedCandidate.startsWith("en")) {
			return "en";
		}
	}

	return null;
};

