export const translateServiceText = (locale: AppLocale, value: string) => {
	if (locale === "en") {
		return value;
	}

	const dictionary =
		locale === "zh-Hant" ? serviceTextEnToZhHant : serviceTextEnToZhHans;

	return dictionary[value] ?? value;
};

export const formatLocaleNumber = (locale: AppLocale, value: number) =>
	new Intl.NumberFormat(locale).format(value);

export const formatLocaleCurrency = (
	locale: AppLocale,
	value: number,
	currency = "HKD"
) =>
	new Intl.NumberFormat(locale === "en" ? "en-HK" : locale, {
		currency,
		maximumFractionDigits: 2,
		minimumFractionDigits: 2,
		style: "currency",
	}).format(value);
